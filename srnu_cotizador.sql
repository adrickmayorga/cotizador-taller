CREATE DATABASE IF NOT EXISTS srnu_cotizador CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE srnu_cotizador;

CREATE TABLE IF NOT EXISTS clientes (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(180) NOT NULL,
    telefono VARCHAR(60) NOT NULL,
    telefono_normalizado VARCHAR(30) NOT NULL,
    email VARCHAR(180) NULL,
    notas VARCHAR(700) NULL,
    activo TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_cliente_telefono (telefono_normalizado),
    KEY idx_cliente_nombre (nombre), KEY idx_cliente_telefono (telefono)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cotizaciones (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    folio VARCHAR(30) NOT NULL UNIQUE,
    cliente VARCHAR(180) NOT NULL,
    telefono VARCHAR(40) NOT NULL,
    cliente_id INT UNSIGNED NULL,
    importado_desde_pdf TINYINT(1) NOT NULL DEFAULT 0,
    pdf_origen_nombre VARCHAR(255) NULL,
    pdf_origen_hash CHAR(64) NULL,
    pdf_folio_origen VARCHAR(60) NULL,
    pdf_origen_archivo VARCHAR(255) NULL,
    vehiculo VARCHAR(180) NOT NULL,
    vehiculo_id INT UNSIGNED NULL,
    fecha DATE NOT NULL,
    requiere_factura ENUM('si','no') NOT NULL DEFAULT 'si',
    subtotal DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    iva DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    msi_plazos LONGTEXT NULL,
    anticipo_tipo VARCHAR(20) NOT NULL DEFAULT 'porcentaje',
    anticipo_valor DECIMAL(12,2) NOT NULL DEFAULT 70.00,
    conservar_anticipo_recibido TINYINT(1) NOT NULL DEFAULT 0,
    anticipo_recibido_monto DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    dividir_anticipo TINYINT(1) NOT NULL DEFAULT 0,
    repartir_igual TINYINT(1) NOT NULL DEFAULT 0,
    anticipo_sergio DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    anticipo_ricardo DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    anticipo_tomas DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    participa_sergio TINYINT(1) NOT NULL DEFAULT 1,
    participa_ricardo TINYINT(1) NOT NULL DEFAULT 1,
    participa_tomas TINYINT(1) NOT NULL DEFAULT 0,
    estado VARCHAR(30) NOT NULL DEFAULT 'Cotización',
    vigencia_dias INT NOT NULL DEFAULT 15,
    dias_trabajo_general_min INT NOT NULL DEFAULT 0,
    dias_trabajo_general_max INT NOT NULL DEFAULT 0,
    aceptada_at DATETIME NULL,
    notas_internas_resumen VARCHAR(700) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    KEY idx_cliente (cliente), KEY idx_vehiculo (vehiculo), KEY idx_fecha (fecha), KEY idx_folio (folio), KEY idx_estado (estado)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cotizacion_items (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    cotizacion_id INT UNSIGNED NOT NULL,
    concepto VARCHAR(500) NOT NULL,
    cantidad DECIMAL(12,2) NOT NULL DEFAULT 1.00,
    precio DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    costo_interno DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    total DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    responsable_sergio TINYINT(1) NOT NULL DEFAULT 0,
    responsable_ricardo TINYINT(1) NOT NULL DEFAULT 0,
    responsable_tomas TINYINT(1) NOT NULL DEFAULT 0,
    garantia_meses INT NOT NULL DEFAULT 0,
    catalogo_id INT NULL,
    tipo_entrega VARCHAR(30) NOT NULL DEFAULT 'inmediata',
    dias_entrega_estimada INT NOT NULL DEFAULT 0,
    dias_trabajo_min INT NOT NULL DEFAULT 0,
    dias_trabajo_max INT NOT NULL DEFAULT 0,
    foto_producto VARCHAR(255) NULL,
    mostrar_foto_pdf TINYINT(1) NOT NULL DEFAULT 1,
    PRIMARY KEY (id), KEY idx_cotizacion (cotizacion_id),
    CONSTRAINT fk_cotizacion_items FOREIGN KEY (cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS pagos (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    cotizacion_id INT UNSIGNED NOT NULL,
    fecha DATE NOT NULL, metodo VARCHAR(50) NOT NULL,
    monto DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    destinatario VARCHAR(30) NOT NULL DEFAULT 'General', notas VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_pago_cotizacion (cotizacion_id),
    CONSTRAINT fk_pagos_cotizacion FOREIGN KEY (cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cotizacion_versiones (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    cotizacion_id INT UNSIGNED NOT NULL, version_no INT NOT NULL,
    snapshot_json LONGTEXT NOT NULL, motivo VARCHAR(255) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_version (cotizacion_id,version_no), KEY idx_version_cotizacion(cotizacion_id),
    CONSTRAINT fk_version_cotizacion FOREIGN KEY (cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS catalogo_servicios (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(220) NOT NULL, descripcion VARCHAR(700) NULL,
    precio_base DECIMAL(12,2) NOT NULL DEFAULT 0.00, costo_base DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    responsable_sergio TINYINT(1) NOT NULL DEFAULT 0, responsable_ricardo TINYINT(1) NOT NULL DEFAULT 0, responsable_tomas TINYINT(1) NOT NULL DEFAULT 0,
    garantia_meses INT NOT NULL DEFAULT 0, tipo_entrega VARCHAR(30) NOT NULL DEFAULT 'inmediata', dias_entrega_estimada INT NOT NULL DEFAULT 0, dias_trabajo_min INT NOT NULL DEFAULT 0, dias_trabajo_max INT NOT NULL DEFAULT 0, foto_producto VARCHAR(255) NULL, categoria VARCHAR(80) NULL, precio_fijo TINYINT(1) NOT NULL DEFAULT 0, menu_codigo VARCHAR(80) NULL, activo TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_catalogo_nombre(nombre), UNIQUE KEY uq_catalogo_menu_codigo(menu_codigo)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ordenes_trabajo (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, cotizacion_id INT UNSIGNED NOT NULL UNIQUE,
    estado VARCHAR(30) NOT NULL DEFAULT 'Vehículo recibido', inventario_descontado TINYINT(1) NOT NULL DEFAULT 0, notas TEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_orden_cotizacion FOREIGN KEY (cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS recepciones (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, cotizacion_id INT UNSIGNED NOT NULL UNIQUE,
    kilometraje VARCHAR(40) NULL, combustible VARCHAR(40) NULL, placas VARCHAR(40) NULL,
    danos TEXT NULL, testigos TEXT NULL, objetos TEXT NULL, notas TEXT NULL,
    firma_cliente VARCHAR(180) NULL, firma_data LONGTEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_recepcion_cotizacion FOREIGN KEY (cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS recepcion_fotos (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, cotizacion_id INT UNSIGNED NOT NULL,
    archivo VARCHAR(255) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_foto_cotizacion(cotizacion_id),
    CONSTRAINT fk_foto_cotizacion FOREIGN KEY (cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS garantias (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, cotizacion_id INT UNSIGNED NOT NULL, item_id INT UNSIGNED NULL,
    concepto VARCHAR(500) NOT NULL, fecha_inicio DATE NOT NULL, fecha_fin DATE NOT NULL,
    notas VARCHAR(700) NULL, estado VARCHAR(20) NOT NULL DEFAULT 'Vigente', created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_garantia_cotizacion(cotizacion_id), KEY idx_garantia_fin(fecha_fin),
    CONSTRAINT fk_garantia_cotizacion FOREIGN KEY (cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS usuarios (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    usuario VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'admin',
    activo TINYINT(1) NOT NULL DEFAULT 1,
    ultimo_acceso DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS configuracion_sistema (
    clave VARCHAR(100) NOT NULL PRIMARY KEY,
    valor TEXT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


CREATE TABLE IF NOT EXISTS agenda_trabajos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,cotizacion_id INT UNSIGNED NULL,titulo VARCHAR(220) NOT NULL,fecha_inicio DATE NOT NULL,hora_inicio TIME NULL,fecha_entrega DATE NULL,hora_entrega TIME NULL,responsable VARCHAR(80) NULL,estado VARCHAR(30) NOT NULL DEFAULT 'Programado',duracion_estimada_horas DECIMAL(8,2) NOT NULL DEFAULT 0,notas VARCHAR(1000) NULL,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,KEY idx_agenda_fecha(fecha_inicio),CONSTRAINT fk_agenda_cot FOREIGN KEY(cotizacion_id) REFERENCES cotizaciones(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS inventario (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,sku VARCHAR(80) NULL UNIQUE,nombre VARCHAR(220) NOT NULL,categoria VARCHAR(120) NULL,unidad VARCHAR(40) NOT NULL DEFAULT 'pieza',stock DECIMAL(12,3) NOT NULL DEFAULT 0,stock_minimo DECIMAL(12,3) NOT NULL DEFAULT 0,costo_unitario DECIMAL(12,2) NOT NULL DEFAULT 0,precio_referencia DECIMAL(12,2) NOT NULL DEFAULT 0,activo TINYINT(1) NOT NULL DEFAULT 1,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS catalogo_insumos (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,catalogo_id INT UNSIGNED NOT NULL,inventario_id INT UNSIGNED NOT NULL,cantidad DECIMAL(12,3) NOT NULL DEFAULT 1,UNIQUE KEY uq_catalogo_insumo(catalogo_id,inventario_id),CONSTRAINT fk_ci_catalogo FOREIGN KEY(catalogo_id) REFERENCES catalogo_servicios(id) ON DELETE CASCADE,CONSTRAINT fk_ci_inventario FOREIGN KEY(inventario_id) REFERENCES inventario(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS movimientos_inventario (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,inventario_id INT UNSIGNED NOT NULL,tipo VARCHAR(30) NOT NULL,cantidad DECIMAL(12,3) NOT NULL,costo_unitario DECIMAL(12,2) NOT NULL DEFAULT 0,referencia_tipo VARCHAR(40) NULL,referencia_id INT UNSIGNED NULL,notas VARCHAR(700) NULL,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,CONSTRAINT fk_mov_inventario FOREIGN KEY(inventario_id) REFERENCES inventario(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS proveedores (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nombre VARCHAR(220) NOT NULL,contacto VARCHAR(180) NULL,telefono VARCHAR(60) NULL,email VARCHAR(180) NULL,pais VARCHAR(100) NULL,tiempo_entrega_dias INT NOT NULL DEFAULT 0,notas VARCHAR(1000) NULL,activo TINYINT(1) NOT NULL DEFAULT 1,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS compras (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,proveedor_id INT UNSIGNED NULL,cotizacion_id INT UNSIGNED NULL,fecha DATE NOT NULL,numero_pedido VARCHAR(120) NULL,tracking VARCHAR(220) NULL,estatus VARCHAR(40) NOT NULL DEFAULT 'Solicitado',inventario_aplicado TINYINT(1) NOT NULL DEFAULT 0,total DECIMAL(12,2) NOT NULL DEFAULT 0,fecha_estimada DATE NULL,notas VARCHAR(1000) NULL,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,CONSTRAINT fk_compra_proveedor FOREIGN KEY(proveedor_id) REFERENCES proveedores(id) ON DELETE SET NULL,CONSTRAINT fk_compra_cot FOREIGN KEY(cotizacion_id) REFERENCES cotizaciones(id) ON DELETE SET NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS compra_items (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,compra_id INT UNSIGNED NOT NULL,inventario_id INT UNSIGNED NULL,descripcion VARCHAR(300) NOT NULL,cantidad DECIMAL(12,3) NOT NULL DEFAULT 1,costo_unitario DECIMAL(12,2) NOT NULL DEFAULT 0,total DECIMAL(12,2) NOT NULL DEFAULT 0,CONSTRAINT fk_compra_item_compra FOREIGN KEY(compra_id) REFERENCES compras(id) ON DELETE CASCADE,CONSTRAINT fk_compra_item_inv FOREIGN KEY(inventario_id) REFERENCES inventario(id) ON DELETE SET NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS gastos (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,fecha DATE NOT NULL,categoria VARCHAR(100) NOT NULL,concepto VARCHAR(300) NOT NULL,monto DECIMAL(12,2) NOT NULL DEFAULT 0,metodo VARCHAR(60) NULL,responsable VARCHAR(80) NULL,cotizacion_id INT UNSIGNED NULL,notas VARCHAR(700) NULL,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,CONSTRAINT fk_gasto_cot FOREIGN KEY(cotizacion_id) REFERENCES cotizaciones(id) ON DELETE SET NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS cierres_caja (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,fecha DATE NOT NULL UNIQUE,efectivo DECIMAL(12,2) NOT NULL DEFAULT 0,transferencias DECIMAL(12,2) NOT NULL DEFAULT 0,tarjeta DECIMAL(12,2) NOT NULL DEFAULT 0,comisiones DECIMAL(12,2) NOT NULL DEFAULT 0,otros DECIMAL(12,2) NOT NULL DEFAULT 0,esperado DECIMAL(12,2) NOT NULL DEFAULT 0,real_conciliado DECIMAL(12,2) NOT NULL DEFAULT 0,diferencia DECIMAL(12,2) NOT NULL DEFAULT 0,notas VARCHAR(1000) NULL,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS vehiculos (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,cliente VARCHAR(180) NOT NULL,telefono VARCHAR(60) NULL,descripcion VARCHAR(220) NOT NULL,placas VARCHAR(50) NULL,vin VARCHAR(80) NULL,kilometraje VARCHAR(50) NULL,color VARCHAR(80) NULL,notas TEXT NULL,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS costos_reales (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,cotizacion_id INT UNSIGNED NOT NULL,fecha DATE NOT NULL,categoria VARCHAR(100) NOT NULL,concepto VARCHAR(300) NOT NULL,monto DECIMAL(12,2) NOT NULL DEFAULT 0,responsable VARCHAR(80) NULL,notas VARCHAR(700) NULL,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,CONSTRAINT fk_costoreal_cot FOREIGN KEY(cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS galeria_trabajos (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,cotizacion_id INT UNSIGNED NOT NULL,etapa VARCHAR(30) NOT NULL DEFAULT 'General',archivo VARCHAR(255) NOT NULL,descripcion VARCHAR(500) NULL,publicable TINYINT(1) NOT NULL DEFAULT 0,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,CONSTRAINT fk_galeria_cot FOREIGN KEY(cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS plantillas (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,nombre VARCHAR(220) NOT NULL,descripcion VARCHAR(700) NULL,activo TINYINT(1) NOT NULL DEFAULT 1,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS plantilla_items (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,plantilla_id INT UNSIGNED NOT NULL,catalogo_id INT UNSIGNED NULL,concepto VARCHAR(500) NOT NULL,cantidad DECIMAL(12,2) NOT NULL DEFAULT 1,precio DECIMAL(12,2) NOT NULL DEFAULT 0,costo_interno DECIMAL(12,2) NOT NULL DEFAULT 0,responsable_sergio TINYINT(1) NOT NULL DEFAULT 0,responsable_ricardo TINYINT(1) NOT NULL DEFAULT 0,responsable_tomas TINYINT(1) NOT NULL DEFAULT 0,garantia_meses INT NOT NULL DEFAULT 0,tipo_entrega VARCHAR(30) NOT NULL DEFAULT 'inmediata',dias_entrega_estimada INT NOT NULL DEFAULT 0,dias_trabajo_min INT NOT NULL DEFAULT 0,dias_trabajo_max INT NOT NULL DEFAULT 0,CONSTRAINT fk_pi_plantilla FOREIGN KEY(plantilla_id) REFERENCES plantillas(id) ON DELETE CASCADE,CONSTRAINT fk_pi_catalogo FOREIGN KEY(catalogo_id) REFERENCES catalogo_servicios(id) ON DELETE SET NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS notas_internas (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,cotizacion_id INT UNSIGNED NOT NULL,nota TEXT NOT NULL,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,CONSTRAINT fk_nota_cot FOREIGN KEY(cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS adjuntos (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,cotizacion_id INT UNSIGNED NOT NULL,archivo VARCHAR(255) NOT NULL,nombre_original VARCHAR(255) NOT NULL,tipo VARCHAR(120) NULL,created_at DATETIME DEFAULT CURRENT_TIMESTAMP,CONSTRAINT fk_adj_cot FOREIGN KEY(cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reparto_ajustes (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,cotizacion_id INT UNSIGNED NOT NULL,persona VARCHAR(30) NOT NULL,monto_objetivo DECIMAL(12,2) NOT NULL DEFAULT 0,notas VARCHAR(500) NULL,updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,UNIQUE KEY uq_reparto_persona(cotizacion_id,persona),CONSTRAINT fk_reparto_cot FOREIGN KEY(cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS postventa_recordatorios (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,cotizacion_id INT UNSIGNED NOT NULL,garantia_id INT UNSIGNED NULL,tipo VARCHAR(80) NOT NULL DEFAULT 'Seguimiento',fecha_recordatorio DATE NOT NULL,descripcion VARCHAR(700) NOT NULL,estado VARCHAR(30) NOT NULL DEFAULT 'Pendiente',created_at DATETIME DEFAULT CURRENT_TIMESTAMP,CONSTRAINT fk_postventa_cot FOREIGN KEY(cotizacion_id) REFERENCES cotizaciones(id) ON DELETE CASCADE,CONSTRAINT fk_postventa_gar FOREIGN KEY(garantia_id) REFERENCES garantias(id) ON DELETE SET NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

